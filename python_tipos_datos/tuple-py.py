# Una tupla permite guardar varios valores.
# Se escribe usando paréntesis ().
# A diferencia de una lista, normalmente no se modifica.

colores = ("rojo", "azul", "verde")

print("Tupla:", colores)
print("Tipo:", type(colores))

print("Primer color:", colores[0])
print("Segundo color:", colores[1])

# Cantidad de elementos
print("Cantidad de colores:", len(colores))

