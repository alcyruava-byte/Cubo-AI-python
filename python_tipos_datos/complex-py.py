# Los números complejos tienen una parte real
# y una parte imaginaria.
# En Python se utiliza la letra j.

numero = 3 + 4j

print("Número complejo:", numero)
print("Tipo:", type(numero))

# Obtener la parte real
print("Parte real:", numero.real)

# Obtener la parte imaginaria
print("Parte imaginaria:", numero.imag)

# Operaciones con números complejos
numero1 = 2 + 3j
numero2 = 1 + 2j

suma = numero1 + numero2

print("Número 1:", numero1)
print("Número 2:", numero2)
print("Suma:", suma)

